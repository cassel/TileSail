#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ $# -lt 1 || ! "$1" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.-]+)?$ ]]; then
    echo "Usage: $0 VERSION [additional xcodebuild options...]" >&2
    exit 1
fi
version="$1"
shift
source_commit="$(git rev-parse HEAD)"
source_short="$(git rev-parse --short HEAD)"
source_dirty=false
if [[ -n "$(git status --porcelain --untracked-files=no)" || -n "$(git ls-files --others --exclude-standard Sources resources script xcode docs dev-docs)" ]]; then
    source_dirty=true
fi
if [[ "$source_dirty" = true && "${TILESAIL_ALLOW_DIRTY_BUILD:-0}" != 1 ]]; then
    echo "Commit source changes first, or set TILESAIL_ALLOW_DIRTY_BUILD=1 for a local preview." >&2
    exit 1
fi
output=".local/installers/TileSail-${version}-universal.dmg"
[[ ! -e "$output" ]] || { echo "Output already exists: $output" >&2; exit 1; }
backup="$(mktemp -d "${TMPDIR:-/tmp}/tilesail-release-sources.XXXXXX")"
cp Sources/Common/versionGenerated.swift "$backup/version.swift"
cp Sources/Common/gitHashGenerated.swift "$backup/hash.swift"
restore_sources() {
    cp "$backup/version.swift" Sources/Common/versionGenerated.swift
    cp "$backup/hash.swift" Sources/Common/gitHashGenerated.swift
    rm -rf "$backup"
}
trap restore_sources EXIT
python3 - "$version" "$source_commit" "$source_short" "$source_dirty" <<'PYSTAMP'
import json, sys
from pathlib import Path
version, commit, short, dirty = sys.argv[1:]
suffix = "-dirty" if dirty == "true" else ""
Path("Sources/Common/versionGenerated.swift").write_text("// FILE IS GENERATED BY generate.sh\npublic let aeroSpaceAppVersion = " + json.dumps(version) + "\n")
Path("Sources/Common/gitHashGenerated.swift").write_text("// FILE IS GENERATED BY generate.sh\npublic let gitHash = " + json.dumps(commit + suffix) + "\npublic let gitShortHash = " + json.dumps(short + suffix) + "\n")
PYSTAMP
xcodebuild -project xcode/AeroSpace.xcodeproj -scheme AeroSpace \
    -configuration Release -destination 'generic/platform=macOS' \
    -derivedDataPath xcode/.xcode-build \
    CODE_SIGNING_ALLOWED=NO ONLY_ACTIVE_ARCH=NO 'ARCHS=arm64 x86_64' \
    MARKETING_VERSION="${version%%-*}" CURRENT_PROJECT_VERSION=1 "$@" build
/System/Library/Frameworks/CoreServices.framework/Versions/Current/Frameworks/LaunchServices.framework/Versions/Current/Support/lsregister \
    -u "$PWD/xcode/.xcode-build/Build/Products/Release/TileSail.app" >/dev/null 2>&1 || true
export TILESAIL_PACKAGING_SOURCE_COMMIT="$source_commit"
export TILESAIL_PACKAGING_SOURCE_DIRTY="$source_dirty"
bash script/package-dmg.sh xcode/.xcode-build/Build/Products/Release/TileSail.app "$output"
